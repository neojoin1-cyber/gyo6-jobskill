function repairString(value) {
  let next = value
  for (const [before, after] of replacements) next = next.replaceAll(before, after)
  for (const [pattern, replacement] of percentagePatterns) next = next.replace(pattern, replacement)
  next = next.replaceAll('합격권', '앱 연습 기본 목표')
  next = next.replace(
    /<table([^>]*)>(?:(?!<\/table>)[\s\S])*?<th>평가영역<\/th><th>비중<\/th><th>확인 포인트<\/th>(?:(?!<\/table>)[\s\S])*?성장가능성(?:(?!<\/table>)[\s\S])*?<\/table>/,
    '<table$1><thead><tr><th>확인 관점</th><th>무엇을 보는가</th></tr></thead><tbody><tr><td><strong>인성·가치관</strong></td><td>성실성, 협업 태도, 조직의 가치와 원칙</td></tr><tr><td><strong>직무역량</strong></td><td>전공지식 활용, 직무 이해, 문제해결</td></tr><tr><td><strong>의사소통</strong></td><td>질문 이해, 논리적 표현, 경청</td></tr><tr><td><strong>성장가능성</strong></td><td>학습의지, 피드백 반영, 도전 경험</td></tr></tbody></table><p><strong>기관마다 항목명과 배점이 다르므로 채용공고·응시 안내를 우선 확인합니다.</strong></p>',
  )
  return next
}

function repair(value) {
  if (typeof value === 'string') return repairString(value)
  if (Array.isArray(value)) return value.map(repair)
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, repair(item)]))
  }
  return value
}

for (const relative of targets) {
  const path = resolve(ROOT, relative)
  const repaired = repair(JSON.parse(readFileSync(path, 'utf8')))
  writeFileSync(path, JSON.stringify(repaired), 'utf8')
  console.log(`[면접 루브릭 경계] 보완 · ${relative}`)
}
