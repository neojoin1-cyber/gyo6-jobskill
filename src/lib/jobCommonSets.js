/**
 * 세트 문항 — 자료 하나로 여러 문항을 이어서 푼다.
 *
 * ### 왜 만들었나
 *
 * 공식 매뉴얼이 밝힌 화면 구성에 이런 대목이 있다.
 *
 *   "여러 문항으로 구성되어 박스 형태로 묶인 세트 문항은
 *    첫 번째 문항부터 순차적으로 풀이하셔야 합니다."
 *
 * 우리에게는 세트 문항이 **한 세트도 없었다.** 문항 하나에 자료 하나씩 붙는
 * 형태만 연습하다가, 시험장에서 처음으로 긴 자료 하나를 놓고 서너 문항을
 * 이어 푸는 상황을 만나게 된다.
 *
 * 형식만 다른 것이 아니라 **읽는 방식이 다르다.** 낱개 문항은 필요한 한 줄만
 * 찾으면 끝나지만, 세트는 자료를 한 번 제대로 읽어 두고 그 이해를 여러
 * 문항에 나눠 쓴다. 첫 문항에서 자료를 대충 읽으면 뒤 문항이 연쇄로 무너진다.
 *
 * ### 어떻게 담나
 *
 *   setId       같은 세트임을 나타내는 값
 *   setOrder    세트 안에서의 순서(1부터)
 *   setTitle    화면에 띄울 세트 이름
 *   context     같은 세트의 모든 문항이 같은 자료를 갖는다(화면에 계속 보인다)
 *
 * 시험지를 짤 때 세트는 흩어지지 않고 순서대로 붙어서 들어간다.
 */

/** 같은 자료를 세트의 모든 문항에 붙인다. 자료가 어긋나면 세트가 깨진다. */
function makeSet({ setId, setTitle, area, lessonId, lessonTitle, context, items }) {
  return items.map((it, i) => ({
    ...it,
    setId, setTitle, setOrder: i + 1, setTotal: items.length,
    area, lessonId, lessonTitle, context,
  }))
}

