// 학습 화면의 두 모드 — 이름과 목적을 한 곳에서 정한다.
//
// ── 무엇이 문제였나 ──────────────────────────────────────────────────────
// 같은 두 모드를 화면마다 다르게 불렀다.
//
//   요점정리가 있는 차시   학습 / 문제
//   그 외 차시             학습 / 게임
//   면접 과목              이론 / 퀴즈 / 실습
//
// 이름이 셋이면 학생은 같은 것인지 다른 것인지 알 수 없다. 더 큰 문제는
// **무엇이 다른지 아무 데도 적혀 있지 않았다**는 것이다. 실제 차이는 이렇다.
//
//   익히기  답을 스스로 떠올린 뒤 펼쳐 확인한다. 채점도 기록도 없다.
//   도전하기 채점된다. 맞히면 XP, 틀리면 오답노트에 들어가고 복습일이 잡힌다.
//
// 이 차이가 곧 두 모드를 나누는 이유다. 틀려도 괜찮은 자리와, 기록이 남는
// 자리를 학생이 구분할 수 있어야 마음 놓고 틀려 보고 마음먹고 점검한다.
// 그래서 이름·아이콘·색·한 줄 설명을 여기 한 곳에 두고 화면들이 가져다 쓴다.

