// 평가틀 빈 칸을 채우는 문항.
//
// 교육부 인증진단의 문제해결은 **4대 내용영역 × 4단계 과정** 으로 출제된다.
// 우리 풀을 그 격자에 얹어 세어 보니 한 칸이 통째로 비어 있었다.
//
//              문제인식  대안탐색  전략수립  평가·성찰
//   자원관리      15       5        67       0   ← 비어 있음
//   정보활용       3       8         6      71
//   기술활용       4      21        31      32
//   시스템적 사고  22      26        82      44
//
// "자원을 나눠 쓰고 난 뒤 그 결정이 맞았는지 되짚는" 문항이 하나도 없었다.
// 자원관리는 배분(전략수립)에 67문항이 몰려 있어, 학생은 나누는 연습만 하고
// 나눈 결과를 재는 연습은 한 번도 하지 못한 채 시험장에 간다. 정보활용·
// 기술활용의 문제인식(3·4문항)도 한 회 시험지를 채우기 어려운 수였다.
//
// 그래서 빈 칸과 얇은 칸을 겨냥해 새로 쓴다. 어느 칸을 채우려고 쓴 문항인지
// psDomain·psProcess 로 문항에 직접 적어 둔다 — 낱말로 짐작하는 자동 분류는
// "결과" 같은 단어 하나에 칸이 바뀌어, 빈 칸을 채우려던 문항이 이미 넘치는
// 칸으로 가 버린다.
//
// 공개된 기출·예시문항을 옮기거나 변형한 것이 아니다. 공개 평가틀이 말하는
// 내용영역·과정의 정의에 맞춰 새로 쓴 연습문항이다.

// 문항 본문은 data/blueprint-fill.json 에 둔다. src 안의 JS 배열로 두면
// 보기 순서 균형·해설 번호 맞춤 같은 복구·검사 스크립트가 이 파일을 보지
// 못한다(스크립트는 src 가 import 하는 data/*.json 만 훑는다). 실제로 처음에
// JS 로 두었더니 새 22문항의 정답이 17개나 1번에 몰려 있었다 — 편향을 지우려고
// 만든 문항이 편향을 새로 심을 뻔했다.
import blueprintFill from '../../data/blueprint-fill.json'

export const JC_BLUEPRINT_FILL = blueprintFill.questions
