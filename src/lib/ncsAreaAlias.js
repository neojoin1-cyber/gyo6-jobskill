// 두 개의 영역 이름 체계를 하나로 맞춘다.
//
// 앱은 NCS 26v1(7영역)과 구 NCS(10영역) 문항을 함께 쓴다. 같은 능력이 은행마다
// 다른 이름으로 저장돼 있어서, 그대로 두면
//   · 영역 선택 화면에 '자기개발능력'과 '자기관리능력'이 나란히 뜨고
//   · "자기개발능력이 약한 학생"에게 26v1 자기관리능력 문항이 영영 안 나온다.
//
// 기준은 ncs2026.js 의 공식 연계표와 같다 — 정보·기술 → 디지털,
// 자원관리·조직이해 → 문제해결, 자기개발 → 자기관리.
export const AREA_ALIAS = {
  자기개발능력: '자기관리능력',
  정보능력: '디지털능력',
  기술능력: '디지털능력',
  자원관리능력: '문제해결능력',
  조직이해능력: '문제해결능력',
}

/** 저장된 영역 이름을 26v1 이름으로 맞춘다. 모르는 이름은 그대로 둔다. */
export function normArea(area) {
  return AREA_ALIAS[area] ?? area ?? ''
}
